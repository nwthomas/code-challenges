from letter_combinations import letterCombinations


def test_handles_one_digit():
    assert letterCombinations("2") == ["a", "b", "c"]


def test_handles_several_digits():
    assert letterCombinations(
        "23") == ["ad", "ae", "af", "bd", "be", "bf", "cd", "ce", "cf"]


